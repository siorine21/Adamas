/** 特性名から効果を引く。知らない特性（手入力など）は undefined */
export function abilityInfo(name: string): AbilityInfo | undefined {
  const key = name.trim();
  if (!key) return undefined;
  const effect = ABILITY_META[key] ?? ABILITY_TEXT[key];
  const calc = ABILITY_CALC[key];
  if (!effect && !calc) return undefined;
  return { name: key, effect: effect ?? "", calc };
}

/** 一覧やメニューの補足に出す1行。効果＋（あれば）倍率 */
export function abilitySummary(name: string): string | undefined {
  const info = abilityInfo(name);
  if (!info) return undefined;
  return info.calc ? `${info.effect}（${info.calc}）` : info.effect;
}
